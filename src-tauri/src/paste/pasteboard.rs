//! Direct `NSPasteboard` access for a restoring paste: a snapshot of every item
//! and type, a marked local-only transient write, and a restore that runs only
//! while the pasteboard still holds that write.
//!
//! Same convention as `macos.rs`: raw `objc_msgSend` cast to the exact
//! signature of each call, which ARM64 requires. Objects from `alloc`/`init`
//! are held as [`Owned`] and released on drop; autoreleased results are used
//! inside an [`AutoreleasePool`] on the calling thread.

use std::ffi::{c_char, c_void, CStr};
use std::sync::{Mutex, MutexGuard, PoisonError};

type Id = *const c_void;
type Sel = *const c_void;

/// Every pasteboard item, as its `(type, bytes)` representations in listing order.
pub(super) type Snapshot = Vec<Vec<(String, Vec<u8>)>>;

/// A snapshot is abandoned once the bytes read so far pass this total.
pub(super) const SNAPSHOT_LIMIT_BYTES: usize = 64 * 1024 * 1024;

const UTF8_PLAIN_TEXT: &str = "public.utf8-plain-text";

/// nspasteboard.org markers: clipboard managers skip transient and concealed
/// content, and auto-generated content was not copied by the user.
const MARKER_TYPES: [&str; 3] = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
];

/// `NSPasteboardContentsCurrentHostOnly`: the contents never reach Universal Clipboard.
const CONTENTS_CURRENT_HOST_ONLY: usize = 1;

const NS_UTF8_STRING_ENCODING: usize = 4;

#[link(name = "AppKit", kind = "framework")]
#[link(name = "objc")]
extern "C" {
    fn objc_getClass(name: *const c_char) -> Id;
    fn sel_registerName(name: *const c_char) -> Sel;
    fn objc_msgSend(); // untyped — cast to the exact signature per call
    fn objc_autoreleasePoolPush() -> *mut c_void;
    fn objc_autoreleasePoolPop(pool: *mut c_void);
}

fn sel(name: &CStr) -> Sel {
    unsafe { sel_registerName(name.as_ptr()) }
}

fn class(name: &CStr) -> Option<Id> {
    let class = unsafe { objc_getClass(name.as_ptr()) };
    (!class.is_null()).then_some(class)
}

unsafe fn send_id(receiver: Id, selector: Sel) -> Id {
    let send: unsafe extern "C" fn(Id, Sel) -> Id = std::mem::transmute(objc_msgSend as *const c_void);
    send(receiver, selector)
}

unsafe fn send_usize(receiver: Id, selector: Sel) -> usize {
    let send: unsafe extern "C" fn(Id, Sel) -> usize = std::mem::transmute(objc_msgSend as *const c_void);
    send(receiver, selector)
}

unsafe fn send_isize(receiver: Id, selector: Sel) -> isize {
    let send: unsafe extern "C" fn(Id, Sel) -> isize = std::mem::transmute(objc_msgSend as *const c_void);
    send(receiver, selector)
}

unsafe fn send_void(receiver: Id, selector: Sel) {
    let send: unsafe extern "C" fn(Id, Sel) = std::mem::transmute(objc_msgSend as *const c_void);
    send(receiver, selector)
}

unsafe fn send_id_usize(receiver: Id, selector: Sel, value: usize) -> Id {
    let send: unsafe extern "C" fn(Id, Sel, usize) -> Id = std::mem::transmute(objc_msgSend as *const c_void);
    send(receiver, selector, value)
}

unsafe fn send_id_id(receiver: Id, selector: Sel, value: Id) -> Id {
    let send: unsafe extern "C" fn(Id, Sel, Id) -> Id = std::mem::transmute(objc_msgSend as *const c_void);
    send(receiver, selector, value)
}

unsafe fn send_isize_usize(receiver: Id, selector: Sel, value: usize) -> isize {
    let send: unsafe extern "C" fn(Id, Sel, usize) -> isize = std::mem::transmute(objc_msgSend as *const c_void);
    send(receiver, selector, value)
}

unsafe fn send_bool_id(receiver: Id, selector: Sel, value: Id) -> bool {
    let send: unsafe extern "C" fn(Id, Sel, Id) -> bool = std::mem::transmute(objc_msgSend as *const c_void);
    send(receiver, selector, value)
}

unsafe fn send_bool_id_id(receiver: Id, selector: Sel, first: Id, second: Id) -> bool {
    let send: unsafe extern "C" fn(Id, Sel, Id, Id) -> bool = std::mem::transmute(objc_msgSend as *const c_void);
    send(receiver, selector, first, second)
}

unsafe fn send_id_ptr_usize(receiver: Id, selector: Sel, pointer: *const c_void, length: usize) -> Id {
    let send: unsafe extern "C" fn(Id, Sel, *const c_void, usize) -> Id =
        std::mem::transmute(objc_msgSend as *const c_void);
    send(receiver, selector, pointer, length)
}

unsafe fn send_id_ptr_usize_usize(
    receiver: Id,
    selector: Sel,
    pointer: *const c_void,
    length: usize,
    value: usize,
) -> Id {
    let send: unsafe extern "C" fn(Id, Sel, *const c_void, usize, usize) -> Id =
        std::mem::transmute(objc_msgSend as *const c_void);
    send(receiver, selector, pointer, length, value)
}

/// Drains the objects autoreleased on this thread since it was pushed. Not
/// `Send`: a pool is popped on the thread that pushed it.
pub(super) struct AutoreleasePool(*mut c_void);

impl AutoreleasePool {
    pub(super) fn push() -> Self {
        Self(unsafe { objc_autoreleasePoolPush() })
    }
}

impl Drop for AutoreleasePool {
    fn drop(&mut self) {
        unsafe { objc_autoreleasePoolPop(self.0) }
    }
}

/// A +1 reference (from `alloc`/`init` or `retain`), released on drop.
#[repr(transparent)]
struct Owned(Id);

impl Owned {
    fn new(object: Id) -> Option<Self> {
        (!object.is_null()).then_some(Self(object))
    }

    unsafe fn alloc_init(class: Id) -> Option<Self> {
        Self::new(send_id(send_id(class, sel(c"alloc")), sel(c"init")))
    }
}

impl Drop for Owned {
    fn drop(&mut self) {
        unsafe { send_void(self.0, sel(c"release")) }
    }
}

unsafe fn ns_string(value: &str) -> Option<Owned> {
    let allocated = send_id(class(c"NSString")?, sel(c"alloc"));
    Owned::new(send_id_ptr_usize_usize(
        allocated,
        sel(c"initWithBytes:length:encoding:"),
        value.as_ptr().cast(),
        value.len(),
        NS_UTF8_STRING_ENCODING,
    ))
}

unsafe fn ns_data(bytes: &[u8]) -> Option<Owned> {
    let allocated = send_id(class(c"NSData")?, sel(c"alloc"));
    Owned::new(send_id_ptr_usize(allocated, sel(c"initWithBytes:length:"), bytes.as_ptr().cast(), bytes.len()))
}

/// Copies an `NSString` into Rust. Call inside an autorelease pool: the UTF-8
/// buffer belongs to the string.
unsafe fn string_from_ns(string: Id) -> Option<String> {
    let utf8 = send_id(string, sel(c"UTF8String")).cast::<c_char>();
    if utf8.is_null() {
        return None;
    }
    CStr::from_ptr(utf8).to_str().ok().map(str::to_owned)
}

unsafe fn data_bytes(data: Id, length: usize) -> Option<Vec<u8>> {
    if length == 0 {
        return Some(Vec::new());
    }
    let bytes = send_id(data, sel(c"bytes")).cast::<u8>();
    (!bytes.is_null()).then(|| std::slice::from_raw_parts(bytes, length).to_vec())
}

/// How a write that replaces the pasteboard contents failed.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum WriteFailure {
    /// Nothing was written; the previous contents are still there.
    Unchanged,
    /// `writeObjects:` failed after the pasteboard was cleared; it is empty.
    Cleared,
}

#[derive(Debug, PartialEq, Eq)]
pub(super) enum RestoreOutcome {
    Restored,
    /// Someone wrote to the pasteboard after us; their contents stay.
    Changed,
    Failed(WriteFailure),
}

/// AppKit's pasteboard type caches are not safe to use from two threads at
/// once, even for different pasteboards. This lock guarantees only that this
/// module's own threads (the paste worker, the restore thread, callers of
/// `copy_to_clipboard`, and tests) never use AppKit's pasteboard at the same
/// time: every message this file sends to a pasteboard, every release of
/// objects it read, and the arboard write in `copy_to_clipboard` hold it.
///
/// Two writers stay outside it and cannot take it: the clipboard plugin's
/// write for the History window's Copy button (its own arboard instance on a
/// tokio worker) and WebKit's own copy on the main thread. Either can still
/// overlap this module's work, which is no worse than before this lock existed.
static APPKIT_PASTEBOARD: Mutex<()> = Mutex::new(());

pub(super) fn exclusive() -> MutexGuard<'static, ()> {
    APPKIT_PASTEBOARD.lock().unwrap_or_else(PoisonError::into_inner)
}

/// A +1 reference to an `NSPasteboard`, released on drop. Not `Send`: the
/// restore thread looks its pasteboard up again by [`Pasteboard::name`].
pub(super) struct Pasteboard(Id);

impl Drop for Pasteboard {
    fn drop(&mut self) {
        let _exclusive = exclusive();
        unsafe { send_void(self.0, sel(c"release")) }
    }
}

impl Pasteboard {
    /// Takes a reference to an autoreleased `board`. Call under the lock,
    /// inside an autorelease pool.
    unsafe fn retain(board: Id) -> Option<Self> {
        (!board.is_null()).then(|| Self(send_id(board, sel(c"retain"))))
    }

    pub(super) fn general() -> Option<Self> {
        let _exclusive = exclusive();
        unsafe {
            let _pool = AutoreleasePool::push();
            Self::retain(send_id(class(c"NSPasteboard")?, sel(c"generalPasteboard")))
        }
    }

    pub(super) fn named(name: &str) -> Option<Self> {
        let _exclusive = exclusive();
        unsafe {
            let _pool = AutoreleasePool::push();
            let name = ns_string(name)?;
            Self::retain(send_id_id(class(c"NSPasteboard")?, sel(c"pasteboardWithName:"), name.0))
        }
    }

    pub(super) fn name(&self) -> Option<String> {
        let _exclusive = exclusive();
        unsafe {
            let _pool = AutoreleasePool::push();
            string_from_ns(send_id(self.0, sel(c"name")))
        }
    }

    pub(super) fn change_count(&self) -> isize {
        let _exclusive = exclusive();
        unsafe { send_isize(self.0, sel(c"changeCount")) }
    }

    /// Reads every item one type at a time. `None` when the pasteboard cannot
    /// list its items or the bytes read pass `limit`. A single representation
    /// is read in full before its size is known.
    pub(super) fn snapshot(&self, limit: usize) -> Option<Snapshot> {
        let _exclusive = exclusive();
        unsafe {
            let _pool = AutoreleasePool::push();
            let items = send_id(self.0, sel(c"pasteboardItems"));
            if items.is_null() {
                return None;
            }
            let (count, object_at_index) = (sel(c"count"), sel(c"objectAtIndex:"));
            let (types_of, data_for_type, length_of) = (sel(c"types"), sel(c"dataForType:"), sel(c"length"));
            let mut snapshot = Vec::new();
            let mut total: usize = 0;
            for item_index in 0..send_usize(items, count) {
                let item = send_id_usize(items, object_at_index, item_index);
                let types = send_id(item, types_of);
                if types.is_null() {
                    continue;
                }
                let mut representations = Vec::new();
                for type_index in 0..send_usize(types, count) {
                    // Frees AppKit's copy of each representation once ours exists.
                    let _representation_pool = AutoreleasePool::push();
                    let pasteboard_type = send_id_usize(types, object_at_index, type_index);
                    let Some(name) = string_from_ns(pasteboard_type) else { continue };
                    let data = send_id_id(item, data_for_type, pasteboard_type);
                    if data.is_null() {
                        continue;
                    }
                    let length = send_usize(data, length_of);
                    total = total.saturating_add(length);
                    if total > limit {
                        return None;
                    }
                    if let Some(bytes) = data_bytes(data, length) {
                        representations.push((name, bytes));
                    }
                }
                if !representations.is_empty() {
                    snapshot.push(representations);
                }
            }
            Some(snapshot)
        }
    }

    /// Replaces the contents with `text` marked transient, concealed and
    /// auto-generated, local to this Mac. Returns the change count after the write.
    pub(super) fn write_transient_text(&self, text: &str) -> Result<isize, WriteFailure> {
        let representations: [(&str, &[u8]); 4] = [
            (UTF8_PLAIN_TEXT, text.as_bytes()),
            (MARKER_TYPES[0], &[]),
            (MARKER_TYPES[1], &[]),
            (MARKER_TYPES[2], &[]),
        ];
        self.replace_contents([representations])?;
        Ok(self.change_count())
    }

    /// Replaces the contents with every item and type in `snapshot`.
    pub(super) fn write_snapshot(&self, snapshot: &Snapshot) -> Result<(), WriteFailure> {
        self.replace_contents(
            snapshot
                .iter()
                .map(|item| item.iter().map(|(pasteboard_type, bytes)| (pasteboard_type.as_str(), bytes.as_slice()))),
        )
    }

    /// Puts `snapshot` back while the change count still equals `change_count`.
    pub(super) fn restore_if_unchanged(&self, change_count: isize, snapshot: &Snapshot) -> RestoreOutcome {
        if self.change_count() != change_count {
            return RestoreOutcome::Changed;
        }
        match self.write_snapshot(snapshot) {
            Ok(()) => RestoreOutcome::Restored,
            Err(failure) => RestoreOutcome::Failed(failure),
        }
    }

    /// Builds every item and the array before clearing, so only a failing
    /// `writeObjects:` can leave the pasteboard empty. Restored contents are
    /// local-only too: the original may have been written that way, and the
    /// pasteboard cannot report how it was.
    fn replace_contents<'a, I, R>(&self, items: I) -> Result<(), WriteFailure>
    where
        I: IntoIterator<Item = R>,
        R: IntoIterator<Item = (&'a str, &'a [u8])>,
    {
        let _exclusive = exclusive();
        unsafe {
            let _pool = AutoreleasePool::push();
            let (Some(item_class), Some(array_class)) = (class(c"NSPasteboardItem"), class(c"NSArray")) else {
                return Err(WriteFailure::Unchanged);
            };
            let set_data = sel(c"setData:forType:");
            let mut objects: Vec<Owned> = Vec::new();
            for representations in items {
                let item = Owned::alloc_init(item_class).ok_or(WriteFailure::Unchanged)?;
                for (pasteboard_type, bytes) in representations {
                    let (Some(pasteboard_type), Some(data)) = (ns_string(pasteboard_type), ns_data(bytes)) else {
                        return Err(WriteFailure::Unchanged);
                    };
                    if !send_bool_id_id(item.0, set_data, data.0, pasteboard_type.0) {
                        return Err(WriteFailure::Unchanged);
                    }
                }
                objects.push(item);
            }
            // `Owned` is a transparent `id`, so the vector is the C array the call expects.
            let array = send_id_ptr_usize(array_class, sel(c"arrayWithObjects:count:"), objects.as_ptr().cast(), objects.len());
            if array.is_null() {
                return Err(WriteFailure::Unchanged);
            }
            send_isize_usize(self.0, sel(c"prepareForNewContentsWithOptions:"), CONTENTS_CURRENT_HOST_ONLY);
            if objects.is_empty() || send_bool_id(self.0, sel(c"writeObjects:"), array) {
                Ok(())
            } else {
                Err(WriteFailure::Cleared)
            }
        }
    }
}

#[cfg(test)]
pub(super) mod test_support {
    use super::*;

    /// A private pasteboard, so tests never touch the user's clipboard.
    pub(in crate::paste) struct UniquePasteboard {
        pub(in crate::paste) board: Pasteboard,
    }

    impl UniquePasteboard {
        pub(in crate::paste) fn new() -> Self {
            let _exclusive = exclusive();
            unsafe {
                let _pool = AutoreleasePool::push();
                let board = send_id(class(c"NSPasteboard").expect("AppKit is loaded"), sel(c"pasteboardWithUniqueName"));
                Self { board: Pasteboard::retain(board).expect("unique pasteboard") }
            }
        }

        pub(in crate::paste) fn write(&self, items: &[&[(&str, &[u8])]]) {
            assert_eq!(self.board.replace_contents(items.iter().map(|item| item.iter().copied())), Ok(()));
        }
    }

    /// Removes the pasteboard from the pasteboard server; `board` then drops
    /// its reference.
    impl Drop for UniquePasteboard {
        fn drop(&mut self) {
            let _exclusive = exclusive();
            unsafe { send_void(self.board.0, sel(c"releaseGlobally")) }
        }
    }

    pub(in crate::paste) fn owned(items: &[&[(&str, &[u8])]]) -> Snapshot {
        items
            .iter()
            .map(|item| item.iter().map(|(pasteboard_type, bytes)| (pasteboard_type.to_string(), bytes.to_vec())).collect())
            .collect()
    }
}

#[cfg(test)]
mod tests {
    use super::test_support::{owned, UniquePasteboard};
    use super::*;

    #[test]
    fn snapshot_and_restore_round_trip_every_item_and_type() {
        let pasteboard = UniquePasteboard::new();
        let original: &[&[(&str, &[u8])]] = &[
            &[(UTF8_PLAIN_TEXT, b"Quarterly numbers"), ("public.html", b"<b>Quarterly</b> numbers")],
            &[("com.sottoasr.test.binary", &[0, 159, 255, 1]), ("com.sottoasr.test.empty", &[])],
        ];
        pasteboard.write(original);

        let snapshot = pasteboard.board.snapshot(SNAPSHOT_LIMIT_BYTES).expect("snapshot");
        assert_eq!(snapshot, owned(original));

        let ours = pasteboard.board.write_transient_text("Dictated text").unwrap();
        assert_eq!(pasteboard.board.restore_if_unchanged(ours, &snapshot), RestoreOutcome::Restored);
        assert_eq!(pasteboard.board.snapshot(SNAPSHOT_LIMIT_BYTES).expect("restored"), owned(original));
    }

    #[test]
    fn restore_is_skipped_after_a_foreign_change() {
        let pasteboard = UniquePasteboard::new();
        pasteboard.write(&[&[(UTF8_PLAIN_TEXT, b"Copied before dictation")]]);
        let snapshot = pasteboard.board.snapshot(SNAPSHOT_LIMIT_BYTES).expect("snapshot");
        let ours = pasteboard.board.write_transient_text("Dictated text").unwrap();

        let copied_during_restore_window: &[&[(&str, &[u8])]] = &[&[(UTF8_PLAIN_TEXT, b"Copied after the paste")]];
        pasteboard.write(copied_during_restore_window);

        assert_eq!(pasteboard.board.restore_if_unchanged(ours, &snapshot), RestoreOutcome::Changed);
        assert_eq!(pasteboard.board.snapshot(SNAPSHOT_LIMIT_BYTES).unwrap(), owned(copied_during_restore_window));
    }

    #[test]
    fn snapshot_over_the_limit_is_abandoned() {
        let pasteboard = UniquePasteboard::new();
        let contents: &[&[(&str, &[u8])]] = &[
            &[("com.sottoasr.test.first", &[1; 30]), ("com.sottoasr.test.second", &[2; 30])],
            &[("com.sottoasr.test.third", &[3; 30])],
        ];
        pasteboard.write(contents);

        assert_eq!(pasteboard.board.snapshot(89), None);
        assert_eq!(pasteboard.board.snapshot(90), Some(owned(contents)));
    }

    #[test]
    fn transient_write_carries_the_three_marker_types() {
        let pasteboard = UniquePasteboard::new();
        pasteboard.write(&[&[(UTF8_PLAIN_TEXT, b"Copied before dictation")]]);
        let before = pasteboard.board.change_count();
        let ours = pasteboard.board.write_transient_text("Dictated text").unwrap();
        // The returned count identifies this write, not the contents it replaced.
        assert!(ours > before, "change count {ours} does not follow {before}");

        let written = pasteboard.board.snapshot(SNAPSHOT_LIMIT_BYTES).expect("snapshot");
        assert_eq!(
            written,
            owned(&[&[
                (UTF8_PLAIN_TEXT, b"Dictated text"),
                ("org.nspasteboard.TransientType", &[]),
                ("org.nspasteboard.ConcealedType", &[]),
                ("org.nspasteboard.AutoGeneratedType", &[]),
            ]])
        );
    }
}
